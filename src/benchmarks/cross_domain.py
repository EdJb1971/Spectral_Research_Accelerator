"""TG4.3 benchmarks: one planted relationship across two real semantic boundaries.

The planted and null records are the same builder at the two ends of one coupling knob.  The
first domain is hourly and measured in kelvin; the second is three-hourly and measured in
megawatts.  Each has a distractor channel.  Nothing in the analysis is told which of the eight
cross-domain directions or four physical lags contains the relationship.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Any, Dict

import numpy as np

from src.benchmarks.core import Benchmark, CheckResult, Outcome, register_benchmark, stage_check
from src.benchmarks.seeding import SeedBundle
from src.core.cross_domain import (
    DomainChannel,
    DomainTimeSeries,
    align_exact,
    confirm_cross_domain,
    sweep_cross_domain,
)
from src.core.domain import AxisSpec, DomainDeclaration
from src.core.precedence import choose_candidates, freeze_precedence, split_with_embargo
from src.core.preregistration import HeldOutLedger


_COMMON_STEPS = 360
_FIRST_CADENCE = 3600.0
_SECOND_CADENCE = 10800.0
_PLANTED_LAG_SECONDS = 21600.0
_LAG_SECONDS = (10800.0, 21600.0, 32400.0, 43200.0)
_SURROGATES = 199
_ALPHA = 0.05


@dataclass(frozen=True)
class CrossDomainBenchmarkData:
    first: DomainTimeSeries
    second: DomainTimeSeries


def _red(length: int, phi: float, rng: np.random.Generator) -> np.ndarray:
    values = np.empty(length, dtype=np.float64)
    values[0] = rng.standard_normal()
    innovation = math.sqrt(max(1.0 - phi * phi, 1e-12))
    for index in range(1, length):
        values[index] = phi * values[index - 1] + innovation * rng.standard_normal()
    return values


def _declaration(name: str, description: str, *, cadence_name: str,
                 floor_frames: int, floor_basis: str) -> DomainDeclaration:
    return DomainDeclaration(
        name=name,
        description=description,
        axes=(AxisSpec(cadence_name, "time", units="s"),
              AxisSpec("channel", "category", ordered=False)),
        licence="Synthetic benchmark; generated by SpectralEarth and redistributable",
        violations=("no_physical_metric", "no_propagation_speed", "no_natural_cycle",
                    "unordered_channels"),
        lag_policy="declared",
        declared_floor_frames=floor_frames,
        declared_floor_basis=floor_basis,
        provenance={"generator": "src.benchmarks.cross_domain"})


def build_cross_domain_pair(bundle: SeedBundle, *, coupling: float = 1.0,
                            common_steps: int = _COMMON_STEPS,
                            planted_lag_seconds: float = _PLANTED_LAG_SECONDS) \
        -> CrossDomainBenchmarkData:
    """Two domains at different cadences, with one optional delayed relationship."""
    if not 0.0 <= coupling <= 1.0:
        raise ValueError("coupling must lie in [0, 1]; got %r" % coupling)
    lag = planted_lag_seconds / _SECOND_CADENCE
    if not float(lag).is_integer() or lag < 1:
        raise ValueError("planted_lag_seconds must be a positive second-domain frame count")
    lag_frames = int(lag)
    native_steps = int(common_steps * (_SECOND_CADENCE / _FIRST_CADENCE))
    rng = bundle.numpy_generator()

    latent_hourly = _red(native_steps, 0.78, rng)
    thermal_noise = _red(native_steps, 0.35, rng)
    thermal_gradient = 284.0 + 3.2 * latent_hourly + 0.25 * rng.standard_normal(native_steps)
    pressure_tendency = 1008.0 + 5.0 * thermal_noise

    common_driver = latent_hourly[::int(_SECOND_CADENCE / _FIRST_CADENCE)]
    independent = _red(common_steps, 0.48, rng)
    target_latent = independent.copy()
    target_latent[lag_frames:] = (
        coupling * common_driver[:-lag_frames]
        + math.sqrt(max(1.0 - coupling * coupling, 0.0))
        * independent[lag_frames:])
    demand = 1450.0 + 210.0 * target_latent + 35.0 * rng.standard_normal(common_steps)
    inventory = 68.0 + 9.0 * _red(common_steps, 0.48, rng)

    first_declaration = _declaration(
        "synthetic_thermal_observatory",
        "An hourly thermal instrument whose channels are instantaneous physical readings.",
        cadence_name="thermal_time", floor_frames=2,
        floor_basis="two hourly sensor-response intervals")
    second_declaration = _declaration(
        "synthetic_demand_ledger",
        "A three-hourly operational ledger whose channels are reported system states.",
        cadence_name="ledger_time", floor_frames=1,
        floor_basis="one three-hour reporting interval")
    first = DomainTimeSeries(
        declaration=first_declaration,
        dataset_id="synthetic-thermal-%d" % bundle.root_seed,
        times_seconds=tuple(np.arange(native_steps, dtype=np.float64) * _FIRST_CADENCE),
        channels=(
            DomainChannel("thermal_gradient", "instantaneous thermal state", "K",
                          tuple(thermal_gradient)),
            DomainChannel("pressure_tendency", "instantaneous pressure tendency", "hPa",
                          tuple(pressure_tendency)),
        ),
        provenance={**bundle.to_provenance(), "role": "first_native_clock"})
    second = DomainTimeSeries(
        declaration=second_declaration,
        dataset_id="synthetic-demand-%d" % bundle.root_seed,
        times_seconds=tuple(np.arange(common_steps, dtype=np.float64) * _SECOND_CADENCE),
        channels=(
            DomainChannel("demand_pressure", "reported electrical demand", "MW",
                          tuple(demand)),
            DomainChannel("inventory_balance", "reported storage balance", "MWh",
                          tuple(inventory)),
        ),
        provenance={**bundle.to_provenance(), "role": "second_native_clock"})
    return CrossDomainBenchmarkData(first=first, second=second)


def build_planted_cross_domain(bundle: SeedBundle, **params: Any) -> CrossDomainBenchmarkData:
    return build_cross_domain_pair(bundle, coupling=1.0, **params)


def build_cross_domain_null(bundle: SeedBundle, **params: Any) -> CrossDomainBenchmarkData:
    return build_cross_domain_pair(bundle, coupling=0.0, **params)


def _truth(planted: bool, *, common_steps: int = _COMMON_STEPS,
           planted_lag_seconds: float = _PLANTED_LAG_SECONDS,
           **_: Any) -> Dict[str, Any]:
    driver = "synthetic_thermal_observatory::thermal_gradient"
    driven = "synthetic_demand_ledger::demand_pressure"
    lag_frames = int(planted_lag_seconds / _SECOND_CADENCE)
    return {
        "planted": bool(planted),
        "expected_confirmations": 1 if planted else 0,
        "driver": driver,
        "driven": driven,
        "lag_seconds": float(planted_lag_seconds),
        "lag_frames_on_common_clock": lag_frames,
        "label": "%s>%s@%d" % (driver, driven, lag_frames),
        "native_cadences_seconds": [_FIRST_CADENCE, _SECOND_CADENCE],
        "common_steps": int(common_steps),
        "family_lag_seconds": list(_LAG_SECONDS),
        "note": ("The thermal channel at t is copied only into the demand channel at "
                 "t + %.0f seconds when planted=True. The other two channels and the reverse "
                 "direction are controls; coupling=0 draws the demand state independently "
                 "through the same code path." % planted_lag_seconds),
    }


def truth_planted_cross_domain(**params: Any) -> Dict[str, Any]:
    return _truth(True, **params)


def truth_cross_domain_null(**params: Any) -> Dict[str, Any]:
    return _truth(False, **params)


def _run(data: CrossDomainBenchmarkData) -> Dict[str, Any]:
    aligned = align_exact(data.first, data.second, name="cross_domain_precedence")
    train, held_out = split_with_embargo(aligned, fraction=0.55)
    generated = sweep_cross_domain(
        train, lag_seconds=_LAG_SECONDS, n_surrogates=_SURROGATES,
        alpha=_ALPHA, study_id="tg4.3-cross-domain")
    chosen = choose_candidates(generated.result)
    ledger = HeldOutLedger()
    seal, frozen = freeze_precedence(
        generated.result, held_out=held_out.identity(),
        sealed_at="2026-08-25T00:00:00Z", n_surrogates=_SURROGATES,
        chosen=chosen, ledger=ledger, study_id="tg4.3-cross-domain")
    seed = int(data.first.provenance["root_seed"]) % (2 ** 31 - 1)
    receipt = confirm_cross_domain(
        seal, frozen, record=held_out, held_out=held_out.identity(), ledger=ledger,
        opened_at="2026-08-25T00:00:01Z", seed=seed)
    return {"aligned": aligned, "train": train, "held_out": held_out,
            "generated": generated, "chosen": frozen, "seal": seal, "receipt": receipt}


def _common_problems(run: Dict[str, Any], truth: Dict[str, Any]) -> list:
    problems = []
    generated, receipt = run["generated"], run["receipt"]
    if generated.result.specification.family_size != 8 * len(_LAG_SECONDS):
        problems.append("the family was %d rather than eight directions by four lags"
                        % generated.result.specification.family_size)
    if generated.metadata["interpolation"] != "none":
        problems.append("alignment interpolated values")
    native = sorted(float(domain["native_cadence_seconds"])
                    for domain in generated.metadata["domains"].values())
    if native != sorted(truth["native_cadences_seconds"]):
        problems.append("native cadences changed from %s to %s"
                        % (truth["native_cadences_seconds"], native))
    if float(run["aligned"].cadence_seconds) != _SECOND_CADENCE:
        problems.append("the exact common clock has cadence %g rather than %g seconds"
                        % (run["aligned"].cadence_seconds, _SECOND_CADENCE))
    if receipt["cross_domain"]["statistic_units"] != "dimensionless":
        problems.append("the cross-domain statistic carries raw source units")
    return problems


@stage_check("4F.cross_domain_recovery")
def _check_planted_relationship(data: CrossDomainBenchmarkData,
                                truth: Dict[str, Any]) -> CheckResult:
    run = _run(data)
    receipt = run["receipt"]
    confirmed = list(receipt["rejected_labels"])
    problems = _common_problems(run, truth)
    if confirmed != [truth["label"]]:
        problems.append("confirmed %s rather than exactly %s"
                        % (confirmed, truth["label"]))
    relationships = {row["label"]: row for row in receipt["relationships"]}
    if truth["label"] in relationships:
        row = relationships[truth["label"]]
        if row["lag_seconds"] != truth["lag_seconds"]:
            problems.append("the frozen physical lag is %g rather than %g seconds"
                            % (row["lag_seconds"], truth["lag_seconds"]))
        if row["driver_operand"]["units"] == row["driven_operand"]["units"]:
            problems.append("the two operands no longer exercise different units")
        if row["driver_operand"]["semantics"] == row["driven_operand"]["semantics"]:
            problems.append("the two operands no longer exercise different semantics")
    best_q = min(receipt["adjusted"]) if receipt["adjusted"] else 1.0
    detail = ("two domains at %.0f- and %.0f-second native cadences aligned by %d exact "
              "timestamps; searched %d cross-domain members without being told pair, "
              "direction or lag; confirmed %s at %.0f seconds with corrected q %.4f"
              % (_FIRST_CADENCE, _SECOND_CADENCE, run["aligned"].length,
                 run["generated"].result.specification.family_size,
                 truth["label"], truth["lag_seconds"], best_q))
    return CheckResult(
        "4F.cross_domain_recovery", Outcome.PASS if not problems else Outcome.FAIL,
        detail if not problems else detail + "; " + "; ".join(problems),
        {"confirmed": confirmed, "smallest_q": float(best_q),
         "family_size": run["generated"].result.specification.family_size,
         "n_frozen": len(run["chosen"]), "common_cadence_seconds": _SECOND_CADENCE})


@stage_check("4F.cross_domain_null")
def _check_null_relationship(data: CrossDomainBenchmarkData,
                             truth: Dict[str, Any]) -> CheckResult:
    run = _run(data)
    receipt = run["receipt"]
    confirmed = list(receipt["rejected_labels"])
    problems = _common_problems(run, truth)
    if confirmed:
        problems.append("confirmed %s although the two domains were generated independently"
                        % confirmed)
    best_q = min(receipt["adjusted"]) if receipt["adjusted"] else 1.0
    detail = ("the same two domains, clocks, units, semantics, eight directions and four "
              "physical lags at coupling zero: %d member(s) frozen from train, none "
              "confirmed on held-out, smallest corrected q %.3f"
              % (len(run["chosen"]), best_q))
    return CheckResult(
        "4F.cross_domain_null", Outcome.PASS if not problems else Outcome.FAIL,
        detail if not problems else detail + "; " + "; ".join(problems),
        {"confirmed": confirmed, "smallest_q": float(best_q),
         "family_size": run["generated"].result.specification.family_size,
         "n_frozen": len(run["chosen"])})


register_benchmark(Benchmark(
    name="planted_cross_domain",
    kind="cross_domain",
    description="Hourly kelvin structure carrying information about a three-hourly megawatt "
                "state at an unknown physical lag, among distractors in both domains.",
    gates=("4F.cross_domain_recovery",),
    build=build_planted_cross_domain,
    known_answer=truth_planted_cross_domain,
    checks=(_check_planted_relationship,),
    params={"common_steps": _COMMON_STEPS,
            "planted_lag_seconds": _PLANTED_LAG_SECONDS},
))


register_benchmark(Benchmark(
    name="cross_domain_null",
    kind="cross_domain",
    description="The same two domains and code path at coupling zero: no cross-domain "
                "relationship exists, so held-out confirmation must remain empty.",
    gates=("4F.cross_domain_null",),
    build=build_cross_domain_null,
    known_answer=truth_cross_domain_null,
    checks=(_check_null_relationship,),
    params={"common_steps": _COMMON_STEPS,
            "planted_lag_seconds": _PLANTED_LAG_SECONDS},
    is_null=True,
))


